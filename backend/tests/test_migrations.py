"""Migration wiring.

Two failures here are silent until they are expensive, so they get tests.

A second Alembic head makes `alembic upgrade head` refuse to run at all, and it
looks like a working tree until the moment anyone tries to deploy.

Bank tables live in `app/bank/models.py`, not `app/models.py`. If Alembic's
metadata does not include that module, the tables read as ones that should no
longer exist, and the next autogenerated migration drops them.
"""

import ast
from pathlib import Path

from alembic.config import Config
from alembic.script import ScriptDirectory

from app.bank.models import AccountRestriction, BankApiKey, BankAuditEvent, BankPartner, BankStaff, RiskFlag, WebhookDelivery, WebhookSubscription
from app.database import Base
from app.models import LinkedAccount, PlatformAuditEvent, SessionRevocation, TrustedDevice

BACKEND_DIR = Path(__file__).resolve().parents[1]
ALEMBIC_INI = BACKEND_DIR / "alembic.ini"
ENV_PY = BACKEND_DIR / "alembic" / "env.py"
RELEASE_READINESS = BACKEND_DIR / "demo docs" / "RELEASE_READINESS.md"


def _script_directory() -> ScriptDirectory:
    config = Config(str(ALEMBIC_INI))
    # CI runs from backend, while local checks often run from the repository
    # root. Resolve this explicitly so both validate the same revision graph.
    config.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    return ScriptDirectory.from_config(config)


def test_there_is_exactly_one_migration_head():
    """`alembic upgrade head` cannot resolve two.

    Two revisions both descending from the same parent is easy to produce when
    two branches are developed at once, and nothing complains until a deploy.
    """
    heads = _script_directory().get_heads()
    assert len(heads) == 1, f"expected a single head, found {heads}"


def test_bank_migration_paths_merge_at_the_expected_head():
    heads = _script_directory().get_heads()
    assert heads == ["0019_member_auth"]


def test_release_readiness_documents_the_current_migration_head():
    """The deployment runbook must not direct a release to an old revision."""
    head = _script_directory().get_heads()[0]
    assert head in RELEASE_READINESS.read_text(encoding="utf-8")


def test_migration_identifiers_fit_the_existing_version_column():
    """Render's established Alembic table uses the standard VARCHAR(32)."""
    revisions = list(_script_directory().walk_revisions())
    too_long = [revision.revision for revision in revisions if len(revision.revision) > 32]
    assert not too_long, f"Alembic revision IDs exceed VARCHAR(32): {too_long}"


