def test_certification_schema_matches_the_models():
    """The 0014 migration and the ORM have to agree, or deploy and dev diverge.

    A column added to a model without a migration reads fine in tests, because
    tests build their schema from the ORM, and then fails against the deployed
    database. The comparison is by name and type rather than by running the
    migration, so a missing column is caught without a database.
    """
    script = _script_directory()
    revision = script.get_revision("0014_certification_schema")
    assert revision is not None

    # Every column the certification models declare must exist in the migration
    # text. Reading the file keeps this honest even when the migration only runs
    # against a live PostgreSQL instance we do not have here.
    source = Path(revision.path).read_text(encoding="utf-8")
    expected = [
        "session_revocations",
        "platform_audit_events",
        "account_restrictions",
        "account_status",
        "session_invalidated_at",
    ]
    missing = [name for name in expected if name not in source]
    assert not missing, f"0014 migration is missing: {missing}"


def test_certification_migration_actually_runs_against_the_previous_schema():
    """Run 0014 for real, on a database shaped like the one 0013 left behind.

    Reading the file for names catches a missing column; it does not catch a
    migration that raises. This executes ``upgrade`` against a minimal pre-0014
    ``users`` table and then asserts the resulting schema through SQLAlchemy's
    inspector, which is the same check a deploy would hit.

    Full ``alembic upgrade head`` cannot be used here: revision 0002 fails on
    SQLite with ``near "ALTER": syntax error`` because it emits ALTER COLUMN,
    which SQLite does not support. That is a separate, pre-existing problem, so
    this exercises the new revision in isolation.
    """
    import sqlalchemy as sa
    from alembic.migration import MigrationContext
    from alembic.operations import Operations

    engine = sa.create_engine("sqlite+pysqlite://")
    with engine.begin() as connection:
        # The subset of the 0013 schema that 0014 alters.
        connection.execute(
            sa.text("CREATE TABLE users (id VARCHAR PRIMARY KEY, name VARCHAR NOT NULL, phone VARCHAR NOT NULL)")
        )
        connection.execute(sa.text("CREATE TABLE bank_partners (id VARCHAR PRIMARY KEY)"))
        connection.execute(sa.text("CREATE TABLE risk_flags (id VARCHAR PRIMARY KEY)"))

        revision = _script_directory().get_revision("0014_certification_schema")
        module = revision.module
        with Operations.context(MigrationContext.configure(connection)):
            module.upgrade()

        inspector = sa.inspect(connection)
        user_columns = {column["name"] for column in inspector.get_columns("users")}
        assert {
            "account_status",
            "restriction_reason",
            "restricted_by",
            "restricted_at",
            "session_invalidated_at",
        } <= user_columns, f"0014 did not add every user column: {user_columns}"

        assert "session_revocations" in inspector.get_table_names()
        assert "platform_audit_events" in inspector.get_table_names()
        assert "account_restrictions" in inspector.get_table_names()

        # Existing rows must come out of the migration usable, not with a null
        # status the authorisation path would then read as "not active".
        connection.execute(sa.text("INSERT INTO users (id, name, phone) VALUES ('u1', 'Old', '+1')"))
        backfilled = connection.execute(sa.text("SELECT account_status FROM users WHERE id = 'u1'")).scalar()
        assert backfilled == "active", "existing rows were not defaulted to active"

        # And it has to come back down cleanly.
        with Operations.context(MigrationContext.configure(connection)):
            module.downgrade()

        inspector = sa.inspect(connection)
        assert "platform_audit_events" not in inspector.get_table_names()
        assert "session_revocations" not in inspector.get_table_names()
        assert "account_restrictions" not in inspector.get_table_names()
        assert "account_status" not in {column["name"] for column in inspector.get_columns("users")}

    engine.dispose()


def test_alembic_metadata_includes_the_bank_models_module():
    """Guards the import in `alembic/env.py` itself.

    Checking `Base.metadata` directly is not enough, because the test process
    imports the bank models itself. What matters is the import Alembic performs,
    so this reads the file rather than re-creating its behaviour.
    """
    tree = ast.parse(ENV_PY.read_text(encoding="utf-8"))
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module)

    assert "app.bank.models" in imported or "app.bank" in imported, (
        "alembic/env.py does not import the bank models, so autogenerate will "
        "propose dropping bank_partners, risk_flags, bank_audit_events and bank_staff"
    )
